#!/usr/bin/env python3
"""Zelda of Warcraft: Beedle, a friendly travelling merchant who repairs and sells potions, food,
water and ammunition at the entrance and the middle of every dungeon and raid (no longer at the
final boss's door). Spots
come from dungeon_vendors.json (solo-wow/tools/compute_dungeon_vendors.py); writes
zelda-sql/004_vendors.sql."""
import json
import math
import os

from build_content import insert, creature_template

HERE = os.path.dirname(os.path.abspath(__file__))
BEEDLE = 190650
GUID_BASE = 9101001
DISPLAY = 7133            # a goblin merchant with a big pack
NPC_FLAGS = 0x4 | 0x4000         # vendor, repair (right-click opens the shop)
# The potion goblin: healing and mana potions only, just outside the Gurubashi Arena (beside Short
# John Mithril) and in the alchemy shop of every capital city.
POTION_GOBLIN = 190651
POTION_GUID_BASE = 9103001
POTION_DISPLAY = 7178     # a goblin alchemist
POTION_ITEMS = [118, 858, 929, 1710, 3928, 13446,       # healing potions
                2455, 3385, 3827, 6149, 13443, 13444]   # mana potions
# (place, map, x, y, z, orientation): between the alchemy vendors of each shop
POTION_SPOTS = [
    ('Gurubashi Arena', 0, -13187.4, 333.6, 40.3, 4.4),
    ('Stormwind', 0, -8990.4, 753.8, 98.41, 0.6),
    ('Ironforge', 0, -4859.96, -1238.78, 501.81, 0.5),
    ('Darnassus', 1, 10066.45, 2344.5, 1321.65, 3.7),
    ('Orgrimmar', 1, 1961.9, -4469.2, 25.78, 3.5),
    ('Thunder Bluff', 1, -1085.06, 27.12, 140.91, 2.2),
    ('Undercity', 0, 1400.32, 380.81, -65.95, 0.0),
]
# The pawnbroker: beside each potion goblin, buys back everything the hero sold since logging in
# (the core keeps the list; script npc_zelda_pawnbroker in zelda_companions.cpp)
PAWNBROKER = 190652
PAWN_GUID_BASE = 9103101
PAWN_DISPLAY = 7130       # a goblin trader
PAWN_TEXTS = [(902001, "Sold something you miss? Happens to everybody, pal. I bought it all off the vendors - "
                       "you can have it back for exactly what they paid you. No markup! ...This time."),
              (902002, "Nothing of yours on my shelves yet. Sell something and come see me - I keep everything "
                       "until you call it a day.")]
ITEMS = [118, 858, 929, 1710, 3928, 13446,          # healing potions
         2455, 3385, 3827, 6149, 13443, 13444,      # mana potions
         159, 1179, 1205, 1708, 1645, 8766,         # water
         4540, 4541, 4542, 4544, 4601, 8950,        # bread
         2512, 2515, 3030, 11285, 2516, 2519, 3033, 11284]   # arrows and shot


def main():
    spots = json.load(open(os.path.join(HERE, 'dungeon_vendors.json')))
    seen, unique = set(), []
    for s in spots:
        if s['spot'] == 'boss door':
            continue                    # none at the end: only at the entrance and the middle
        key = (s['map'], round(s['x']), round(s['y']))
        if key not in seen:
            seen.add(key)
            unique.append(s)
    t = creature_template(BEEDLE, 'Beedle', 'Travelling Merchant', DISPLAY, 35, 0, 60, 1, '')
    t['NpcFlags'] = NPC_FLAGS
    t['UnitFlags'] = 0x100 | 0x200         # immune to players and creatures (and friendly to all)
    t['ExperienceMultiplier'] = 0
    out = ['-- Zelda of Warcraft: Beedle the travelling merchant in every dungeon and raid. Generated by',
           '-- build_vendors.py; applied by the server at startup.',
           'DELETE FROM `creature` WHERE `id` = %d;' % BEEDLE,
           'DELETE FROM `creature_template` WHERE `Entry` = %d;' % BEEDLE,
           'DELETE FROM `npc_vendor` WHERE `entry` = %d;' % BEEDLE, '']
    out.append(insert('creature_template', [t]))
    spawns = [dict(guid=GUID_BASE + i, id=BEEDLE, map=s['map'], spawnMask=1, position_x=s['x'], position_y=s['y'],
                   position_z=s['z'], orientation=s['o'], spawntimesecsmin=300, spawntimesecsmax=300, spawndist=0,
                   MovementType=0) for i, s in enumerate(unique)]
    out.append(insert('creature', spawns))
    out.append(insert('npc_vendor', [dict(entry=BEEDLE, item=i, maxcount=0, incrtime=0, slot=n, condition_id=0)
                                     for n, i in enumerate(ITEMS)]))
    # the potion goblin
    g = creature_template(POTION_GOBLIN, 'Fizzbang Bottlecork', 'Potion Goblin', POTION_DISPLAY, 35, 0, 50, 1, '')
    g['NpcFlags'] = 0x4                   # vendor
    g['UnitFlags'] = 0x100 | 0x200
    g['ExperienceMultiplier'] = 0
    out += ['DELETE FROM `creature` WHERE `id` = %d;' % POTION_GOBLIN,
            'DELETE FROM `creature_template` WHERE `Entry` = %d;' % POTION_GOBLIN,
            'DELETE FROM `npc_vendor` WHERE `entry` = %d;' % POTION_GOBLIN, '']
    out.append(insert('creature_template', [g]))
    out.append(insert('creature', [dict(guid=POTION_GUID_BASE + i, id=POTION_GOBLIN, map=m, spawnMask=1, position_x=x,
                                        position_y=y, position_z=z, orientation=o, spawntimesecsmin=300,
                                        spawntimesecsmax=300, spawndist=0, MovementType=0)
                                   for i, (_, m, x, y, z, o) in enumerate(POTION_SPOTS)]))
    out.append(insert('npc_vendor', [dict(entry=POTION_GOBLIN, item=i, maxcount=0, incrtime=0, slot=n, condition_id=0)
                                     for n, i in enumerate(POTION_ITEMS)]))
    # the pawnbroker, a step to the side of each potion goblin
    b = creature_template(PAWNBROKER, 'Grizzle Pawnwick', 'Pawnbroker', PAWN_DISPLAY, 35, 0, 50, 1, 'npc_zelda_pawnbroker')
    b['NpcFlags'] = 0x1                   # gossip
    b['UnitFlags'] = 0x100 | 0x200
    b['ExperienceMultiplier'] = 0
    out += ['DELETE FROM `creature` WHERE `id` = %d;' % PAWNBROKER,
            'DELETE FROM `creature_template` WHERE `Entry` = %d;' % PAWNBROKER,
            'DELETE FROM `npc_text` WHERE `ID` IN (%s);' % ','.join(str(t[0]) for t in PAWN_TEXTS), '']
    out.append(insert('creature_template', [b]))
    out.append(insert('creature', [dict(guid=PAWN_GUID_BASE + i, id=PAWNBROKER, map=m, spawnMask=1,
                                        position_x=round(x + 1.8 * math.cos(o + math.pi / 2), 2),
                                        position_y=round(y + 1.8 * math.sin(o + math.pi / 2), 2), position_z=z,
                                        orientation=o, spawntimesecsmin=300, spawntimesecsmax=300, spawndist=0,
                                        MovementType=0)
                                   for i, (_, m, x, y, z, o) in enumerate(POTION_SPOTS)]))
    out.append(insert('npc_text', [dict(ID=t, text0_0=text, text0_1=text, lang0=0, prob0=1, em0_0=0, em0_1=1)
                                   for t, text in PAWN_TEXTS]))
    with open(os.path.join(HERE, 'zelda-sql', '004_vendors.sql'), 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', len(spawns), 'Beedle spawns')


if __name__ == '__main__':
    main()
