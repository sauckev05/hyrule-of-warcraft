def esc(v):
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace('\\', '\\\\').replace("'", "''") + "'"


def main():
    out = ['-- Zelda of Warcraft: the Gurubashi Arena challenge (generated by build_arena.py)',
           '-- Applied by the server at startup; safe to apply again.']
    ids = ','.join(str(f[0]) for f in FIGHTERS)
    out.append('DELETE FROM `creature_ai_scripts` WHERE `creature_id` IN (%s);' % ids)
    out.append('DELETE FROM `creature_template` WHERE `Entry` IN (%s);' % ids)
    cols = ['Entry', 'Name', 'SubName', 'MinLevel', 'MaxLevel', 'DisplayId1', 'DisplayIdProbability1', 'Faction',
            'Scale', 'CreatureType', 'InhabitType', 'RegenerateStats', 'NpcFlags', 'UnitFlags', 'SpeedWalk',
            'SpeedRun', 'UnitClass', 'Rank', 'HealthMultiplier', 'PowerMultiplier', 'DamageMultiplier',
            'ArmorMultiplier', 'ExperienceMultiplier', 'MeleeBaseAttackTime', 'RangedBaseAttackTime',
            'EquipmentTemplateId', 'GossipMenuId', 'AIName', 'ScriptName']
    rows = []
    for (entry, name, sub, display, equip, cls, ctype, scale, dmg, atk) in FIGHTERS:
        rows.append([entry, name, sub, 35, 35, display, 100, 14, scale, ctype, 1, 1, 0, 0, 1.0, 1.14286, cls, 1,
                     1.0, 1.0, dmg, 1.0, 1.0, atk, 2000, equip, 0, 'EventAI', ''])
    out.append('INSERT INTO `creature_template` (%s) VALUES\n%s;' % (
        ','.join('`%s`' % c for c in cols), ',\n'.join('(' + ','.join(esc(v) for v in r) + ')' for r in rows)))
    ai = []
    n = {}
    for (cid, event, params, spell, target) in ABILITIES:
        n[cid] = n.get(cid, 0) + 1
        aid = cid * 100 + n[cid]
        flags = 1 if event == TIMER else 0
        ai.append('(%d,%d,%d,0,100,%d,%d,%d,%d,%d,%d,%d,11,%d,%d,0,0,0,0,0,0,0,0,0,%s)' % (
            aid, cid, event, flags, *params, spell, target, esc('Zelda arena: %d cast %d' % (cid, spell))))
    out.append('INSERT INTO `creature_ai_scripts` (`id`,`creature_id`,`event_type`,`event_inverse_phase_mask`,'
               '`event_chance`,`event_flags`,`event_param1`,`event_param2`,`event_param3`,`event_param4`,'
               '`event_param5`,`event_param6`,`action1_type`,`action1_param1`,`action1_param2`,`action1_param3`,'
               '`action2_type`,`action2_param1`,`action2_param2`,`action2_param3`,`action3_type`,`action3_param1`,'
               '`action3_param2`,`action3_param3`,`comment`) VALUES\n%s;' % ',\n'.join(ai))
    out.append('UPDATE `quest_template` SET `Details` = %s, `Objectives` = %s WHERE `entry` = 7838;'
               % (esc(GRANDMASTER_DETAILS), esc(GRANDMASTER_OBJECTIVES)))
    # Arena Grand Master: no use, a shield that rises by itself near death (the core, Zelda.ArenaGrandMasterCooldown)
    out.append('UPDATE `item_template` SET `spellid_2` = 0, `spelltrigger_2` = 0, `spellcooldown_2` = -1, '
               '`spellcategory_2` = 0, `spellcategorycooldown_2` = -1, `description` = %s WHERE `entry` = 19024;'
               % esc('Equip: When a blow would leave you under 10% health, a champion\'s shield absorbs 750 damage. '
                     '(5 min cooldown)'))
    path = os.path.join(HERE, 'zelda-sql', '014_arena.sql')
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
