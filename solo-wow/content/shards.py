def add_displays(rows, add_string):
    """ItemDisplayInfo rows for the shards, cloned from GEM_LOOK with their own icons."""
    ours = {display_of(s[0]) for s in SHARDS}
    rows[:] = [r for r in rows if r[0] not in ours]
    base = next(r for r in rows if r[0] == GEM_LOOK)
    for s in SHARDS:
        row = list(base)
        row[0] = display_of(s[0])
        row[5] = add_string(icon_of(s[0]))
        rows.append(row)
    rows.sort(key=lambda r: r[0])


def _tint(image, hue, sat, val):
    """Recolour an RGBA image: its brightness kept, its colour replaced (an overlay blend)."""
    import colorsys
    r, g, b = colorsys.hsv_to_rgb(hue / 360.0, sat, 1.0)
    target = (r, g, b)
    out = []
    for pr, pg, pb, pa in image.getdata():
        lum = (0.299 * pr + 0.587 * pg + 0.114 * pb) / 255.0
        px = []
        for c in target:
            v = 2 * c * lum if lum < 0.5 else 1 - 2 * (1 - c) * (1 - lum)
            px.append(max(0, min(255, int(round(v * val * 255)))))
        out.append((px[0], px[1], px[2], pa))
    tinted = image.copy()
    tinted.putdata(out)
    return tinted


def blp_raw1(image):
    """A BLP2 with a 256-colour palette (compression 1), no alpha, and every mip level."""
    import struct
    from PIL import Image
    image = image.convert('RGB')
    w, h = image.size
    pal_img = image.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = pal_img.getpalette()[:768]
    palette += [0] * (768 - len(palette))
    levels = []
    lw, lh = w, h
    while True:
        lvl = image.resize((lw, lh), Image.LANCZOS) if (lw, lh) != (w, h) else image
        levels.append(lvl.quantize(palette=pal_img, dither=Image.Dither.NONE).tobytes())
        if lw == 1 and lh == 1:
            break
        lw, lh = max(1, lw // 2), max(1, lh // 2)
    header_size = 4 + 4 + 4 + 8 + 64 + 64 + 1024
    offsets, sizes, pos = [], [], header_size
    for data in levels:
        offsets.append(pos)
        sizes.append(len(data))
        pos += len(data)
    offsets += [0] * (16 - len(offsets))
    sizes += [0] * (16 - len(sizes))
    out = bytearray(b'BLP2')
    out += struct.pack('<I', 1)                    # type 1: direct (palette or DXT)
    out += struct.pack('<BBBB', 1, 0, 0, 1)        # compression 1 (palette), alpha 0, alpha type, has mips
    out += struct.pack('<II', w, h)
    out += struct.pack('<16I', *offsets)
    out += struct.pack('<16I', *sizes)
    for i in range(256):
        rr, gg, bb = palette[i * 3:i * 3 + 3]
        out += bytes((bb, gg, rr, 0))              # BGRA
    for data in levels:
        out += data
    return bytes(out)


def icon_files(source_blp_bytes):
    """{MPQ path: BLP bytes}: each shard's icon, the glowing shard recoloured to its dungeon."""
    import io
    from PIL import Image
    base = Image.open(io.BytesIO(source_blp_bytes)).convert('RGBA')
    files = {}
    for s in SHARDS:
        hue, sat, val = s[6]
        files['Interface\\Icons\\%s.blp' % icon_of(s[0])] = blp_raw1(_tint(base, hue, sat, val))
    return files
