DISPLAY_BASE = 60200          # ItemDisplayInfo rows of the shards: DISPLAY_BASE + (item - 191100)


def display_of(item):
    return DISPLAY_BASE + item - SHARDS[0][0]


def icon_of(item):
    return 'INV_Zelda_Shard_%d' % (item - SHARDS[0][0])


def sql_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_sql(path):
    out = ['-- Zelda of Warcraft: dungeon clears and their Crystal Shards (generated by shards.py)',
           '-- Applied by the server at startup; safe to apply again.',
           'CREATE TABLE IF NOT EXISTS `zelda_dungeon_clear` (`map` INT UNSIGNED NOT NULL, `section` TINYINT UNSIGNED NOT NULL, '
           '`name` VARCHAR(64) NOT NULL, `item` INT UNSIGNED NOT NULL, `raid` TINYINT UNSIGNED NOT NULL DEFAULT 0, '
           '`min_x` FLOAT NOT NULL, `max_x` FLOAT NOT NULL, `min_y` FLOAT NOT NULL, `max_y` FLOAT NOT NULL, '
           'PRIMARY KEY (`map`, `section`)) ENGINE=InnoDB DEFAULT CHARSET=utf8;',
           'DELETE FROM `zelda_dungeon_clear`;']
    rows = []
    for item, m, sec, name, raid, box, _ in SHARDS:
        b = box or (-99999, 99999, -99999, 99999)
        rows.append('(%d,%d,%s,%d,%d,%d,%d,%d,%d)' % (m, sec, sql_str(name), item, raid, *b))
    out.append('INSERT INTO `zelda_dungeon_clear` (`map`,`section`,`name`,`item`,`raid`,`min_x`,`max_x`,`min_y`,`max_y`) VALUES\n'
               + ',\n'.join(rows) + ';')
    ids = ','.join(str(s[0]) for s in SHARDS)
    out.append('DELETE FROM `item_template` WHERE `entry` IN (%s);' % ids)
    rows = []
    for item, m, sec, name, raid, box, _ in SHARDS:
        rows.append('(%d,15,0,%s,%d,%d,0,1,0,0,0,-1,-1,%d,0,1,1,1,%s,4)'
                    % (item, sql_str('Crystal Shard of ' + name), display_of(item), 4 if raid else 3,
                       60 if raid else 40,
                       sql_str('Every foe in %s has fallen before you.' % name)))
    out.append('INSERT INTO `item_template` (`entry`,`class`,`subclass`,`name`,`displayid`,`Quality`,`Flags`,`BuyCount`,'
               '`BuyPrice`,`SellPrice`,`InventoryType`,`AllowableClass`,`AllowableRace`,`ItemLevel`,`RequiredLevel`,'
               '`stackable`,`maxcount`,`bonding`,`description`,`Material`) VALUES\n' + ',\n'.join(rows) + ';')
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', path)


