#!/usr/bin/env python3
"""Builds zelda-sql/002_sets.sql (items, boss drops and set bonuses) and the ZeldaHUD addon's
setsdata.lua (set tooltips) from sets.py. armor/durability/block come from set_refs.json, averaged
from real items of the same armor type, slot and item level."""
import json
import os
import random

from build_content import esc, insert
from sets import SETS, SLOTS, BONUS_TYPES, BONUS_TEXT, DROP_CHANCE

HERE = os.path.dirname(os.path.abspath(__file__))
REFS = json.load(open(os.path.join(HERE, 'set_refs.json')))
ADDON = os.path.join(HERE, '..', 'package', 'addons', 'ZeldaHUD', 'setsdata.lua')

# warrior-minded, but random: strength, agility, stamina, sometimes spirit
STAT_POOL = [(4, 4), (3, 3), (7, 4), (6, 1)]       # (stat type, weight)


def roll_stats(entry, budget):
    rng = random.Random(entry * 7919)
    count = 2 if budget < 12 else rng.choice([2, 3, 3])
    chosen = []
    pool = list(STAT_POOL)
    while len(chosen) < count and pool:
        total = sum(w for _, w in pool)
        pick = rng.uniform(0, total)
        for i, (stat, w) in enumerate(pool):
            pick -= w
            if pick <= 0:
                chosen.append(stat)
                pool.pop(i)
                break
    shares = [rng.uniform(0.6, 1.4) for _ in chosen]
    scale = budget / sum(shares)
    values = [max(1, int(round(s * scale))) for s in shares]
    return list(zip(chosen, values))


def item_row(s, piece):
    entry, slot, name, display, _boss, _where = piece
    inv, factor = SLOTS[slot]
    ilvl = s['level'] + 5
    row = {'entry': entry, 'class': 4, 'name': name, 'displayid': display, 'Quality': 3, 'Flags': 0, 'BuyCount': 1,
           'InventoryType': inv, 'AllowableClass': -1, 'AllowableRace': -1, 'ItemLevel': ilvl,
           'RequiredLevel': s['level'], 'maxcount': 0, 'stackable': 1, 'bonding': 1, 'description': '',
           'sheath': 0, 'armor': 0, 'block': 0, 'MaxDurability': 0, 'itemset': 0, 'DisenchantID': 0}
    if slot == 'tabard':
        row.update(subclass=0, Material=7)
    elif slot == 'shield':
        ref = REFS['6:14:%d' % ilvl]
        row.update(subclass=6, Material=1, sheath=4, armor=ref['armor'], block=ref['block'],
                   MaxDurability=ref['durability'])
    else:
        ref = REFS['%d:%d:%d' % (s['subclass'], inv, ilvl)]
        row.update(subclass=s['subclass'], Material=s['material'], armor=ref['armor'],
                   MaxDurability=ref['durability'])
    stats = roll_stats(entry, int(round(ilvl * 0.75 * factor)))
    for i in range(1, 11):
        row['stat_type%d' % i] = 0
        row['stat_value%d' % i] = 0
    for i, (stat, value) in enumerate(stats, start=1):
        row['stat_type%d' % i] = stat
        row['stat_value%d' % i] = value
    row['SellPrice'] = int(ilvl * ilvl * 3 * max(factor, 0.5))
    row['BuyPrice'] = row['SellPrice'] * 5
    return row


def bonus_line(pieces, kind, value):
    return '(%d) Set: %s' % (pieces, BONUS_TEXT[kind] % value)


def lua_str(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    out = ['-- Zelda of Warcraft armor sets. Generated by build_sets.py - edit sets.py.\n'
           '-- Applied by the server at startup (zelda-sql); safe to apply again.\n']
    out.append("""CREATE TABLE IF NOT EXISTS `zelda_itemset_item` (
  `item` int unsigned NOT NULL PRIMARY KEY,
  `set_id` int unsigned NOT NULL
) ENGINE=MyISAM DEFAULT CHARSET=utf8 COMMENT='Zelda of Warcraft: armor set pieces';
CREATE TABLE IF NOT EXISTS `zelda_itemset_bonus` (
  `set_id` int unsigned NOT NULL,
  `pieces` tinyint unsigned NOT NULL,
  `bonus_type` tinyint unsigned NOT NULL,
  `value` float NOT NULL
) ENGINE=MyISAM DEFAULT CHARSET=utf8 COMMENT='Zelda of Warcraft: armor set bonuses (see ZeldaCommands.cpp)';
""")
    entries = [p[0] for s in SETS for p in s['pieces']]
    item_list = ','.join(map(str, entries))
    out.append('DELETE FROM `item_template` WHERE `entry` IN (%s);\n' % item_list)
    out.append('DELETE FROM `creature_loot_template` WHERE `item` IN (%s);\n' % item_list)
    out.append('DELETE FROM `zelda_itemset_item`;\nDELETE FROM `zelda_itemset_bonus`;\n')

    items, loot, set_items, bonuses = [], [], [], []
    lua = ['-- Zelda of Warcraft armor sets, for the set tooltips. Generated by build_sets.py.',
           'ZELDA_SETS = {']
    for s in SETS:
        for piece in s['pieces']:
            items.append(item_row(s, piece))
            loot.append(dict(entry=piece[4], item=piece[0], ChanceOrQuestChance=DROP_CHANCE, groupid=0,
                             mincountOrRef=1, maxcount=1, condition_id=0, comments='Zelda armor set: ' + s['name']))
            set_items.append(dict(item=piece[0], set_id=s['id']))
        for pieces, kind, value in s['bonuses']:
            bonuses.append(dict(set_id=s['id'], pieces=pieces, bonus_type=BONUS_TYPES[kind], value=float(value)))
        lua.append('  [%d] = {' % s['id'])
        lua.append('    name = %s,' % lua_str(s['name']))
        lua.append('    items = { %s },' % ', '.join(
            '{ %d, %s, %s }' % (p[0], lua_str(p[2]), lua_str(p[5])) for p in s['pieces']))
        lua.append('    bonuses = { %s },' % ', '.join(
            '{ %d, %s }' % (pieces, lua_str(bonus_line(pieces, kind, value))) for pieces, kind, value in s['bonuses']))
        lua.append('  },')
    lua.append('}')
    lua.append('')

    out.append(insert('item_template', items))
    out.append(insert('creature_loot_template', loot))
    out.append(insert('zelda_itemset_item', set_items))
    out.append(insert('zelda_itemset_bonus', bonuses))

    path = os.path.join(HERE, 'zelda-sql', '002_sets.sql')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    with open(ADDON, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lua))
    print('wrote', path, 'and', os.path.normpath(ADDON), '-', len(items), 'items')
    for it in items:
        stats = ', '.join('+%d %s' % (it['stat_value%d' % i], {3: 'Agi', 4: 'Str', 5: 'Int', 6: 'Spi', 7: 'Sta'}[it['stat_type%d' % i]])
                          for i in range(1, 4) if it['stat_type%d' % i])
        print('  %-36s ilvl %d  armor %4d  %s' % (it['name'], it['ItemLevel'], it['armor'], stats))


if __name__ == '__main__':
    main()
