#!/usr/bin/env python3
"""Builds zelda-sql/001_companions.sql from story.py: the four companions, their story characters,
quests, quest items, drops and dialogue. The server applies zelda-sql/*.sql by itself at startup
(ZeldaApplyContentSql), and CI loads the file into a real database to check it."""
import json
import os
from story import STORY_NPCS, COMPANIONS, QUEST_ITEMS, Q, KATRANA_TEXTS, CAPTIVE_TEXT

HERE = os.path.dirname(os.path.abspath(__file__))
REWARDS = {int(k): v for k, v in json.load(open(os.path.join(HERE, 'rewards.json'))).items()}
GUID_BASE = 9100001
NPC_FLAG_GOSSIP_QUEST = 3
QUEST_TYPE = {'': 0, 'dungeon': 81, 'raid': 62}
LYRA_CAPTIVE = 190101
KATRANA = 1749
ONYXIA_QUEST = 90110


def esc(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace('\\', '\\\\').replace("'", "''") + "'"


def insert(table, rows):
    if not rows:
        return ''
    cols = list(rows[0].keys())
    values = ',\n'.join('(' + ','.join(esc(r[c]) for c in cols) + ')' for r in rows)
    return 'INSERT INTO `%s` (%s) VALUES\n%s;\n' % (table, ','.join('`%s`' % c for c in cols), values)


def creature_template(entry, name, subname, display, faction, equipment, level, unit_class, script, health=1.0, power=1.0):
    return dict(Entry=entry, Name=name, SubName=subname, MinLevel=level, MaxLevel=level,
                DisplayId1=display, DisplayIdProbability1=100, Faction=faction, Scale=1.0,
                CreatureType=7, InhabitType=3, RegenerateStats=3, NpcFlags=NPC_FLAG_GOSSIP_QUEST,
                SpeedWalk=1.0, SpeedRun=1.14286, UnitClass=unit_class, Rank=0,
                HealthMultiplier=health, PowerMultiplier=power, DamageMultiplier=1.0, ArmorMultiplier=1.0,
                ExperienceMultiplier=0, MeleeBaseAttackTime=2000, RangedBaseAttackTime=2000,
                EquipmentTemplateId=equipment, GossipMenuId=0, AIName='', ScriptName=script)


def npc_text(id_, text):
    return dict(ID=id_, text0_0=text, text0_1=text, lang0=0, prob0=1, em0_0=0, em0_1=1)


def main():
    out = ['-- Zelda of Warcraft: the companions and their story. Generated by build_content.py - edit story.py.\n'
           '-- Applied by the server at startup (zelda-sql); safe to apply again.\n']

    entries = [n[0] for n in STORY_NPCS] + [s[0] for c in COMPANIONS.values() for s in c['stages']]
    entry_list = ','.join(map(str, entries))
    quest_list = ','.join(str(q['id']) for q in Q)
    item_list = ','.join(str(i[0]) for i in QUEST_ITEMS)

    out.append("""CREATE TABLE IF NOT EXISTS `zelda_stage` (
  `entry` int unsigned NOT NULL PRIMARY KEY,
  `show_quest` int unsigned NOT NULL DEFAULT 0,
  `show_state` tinyint unsigned NOT NULL DEFAULT 1,
  `hide_quest` int unsigned NOT NULL DEFAULT 0,
  `hide_state` tinyint unsigned NOT NULL DEFAULT 1
) ENGINE=MyISAM DEFAULT CHARSET=utf8 COMMENT='Zelda of Warcraft: which companion spawn a hero sees, by quest progress';
""")
    out.append('DELETE FROM `zelda_stage`;\n')
    out.append('DELETE FROM `creature` WHERE `id` IN (%s);\n' % entry_list)
    out.append('DELETE FROM `creature_template` WHERE `Entry` IN (%s);\n' % entry_list)
    out.append('DELETE FROM `creature_template_addon` WHERE `entry` IN (%s);\n' % entry_list)
    out.append('DELETE FROM `creature_questrelation` WHERE `quest` IN (%s);\n' % quest_list)
    out.append('DELETE FROM `creature_involvedrelation` WHERE `quest` IN (%s);\n' % quest_list)
    out.append('DELETE FROM `quest_template` WHERE `entry` IN (%s);\n' % quest_list)
    out.append('DELETE FROM `item_template` WHERE `entry` IN (%s);\n' % item_list)
    out.append('DELETE FROM `creature_loot_template` WHERE `item` IN (%s);\n' % item_list)
    out.append('DELETE FROM `npc_text` WHERE `ID` BETWEEN 900000 AND 900999;\n')
    out.append('DELETE FROM `gossip_menu` WHERE `entry` BETWEEN 190000 AND 190999;\n')

    templates, spawns, addons, texts, menus, stages = [], [], [], [], [], []
    guid = GUID_BASE

    # story characters
    for i, (entry, name, sub, display, faction, equip, level, pos, greeting) in enumerate(STORY_NPCS):
        t = creature_template(entry, name, sub, display, faction, equip, level, 1, '')
        t['GossipMenuId'] = entry
        templates.append(t)
        texts.append(npc_text(900001 + i, greeting))
        menus.append(dict(entry=entry, text_id=900001 + i, script_id=0, condition_id=0))
        m, x, y, z, o = pos
        spawns.append(dict(guid=guid, id=entry, map=m, spawnMask=1, position_x=x, position_y=y, position_z=z,
                           orientation=o, spawntimesecsmin=60, spawntimesecsmax=60, spawndist=0, MovementType=0))
        guid += 1

    # the companions, one spawn per chapter
    for key, c in COMPANIONS.items():
        base = {'lyra': 900100, 'faelin': 900200, 'durza': 900300, 'vesper': 900400}[key]
        texts.append(npc_text(base + 1, c['greeting']))
        texts.append(npc_text(base + 10, c['about']))
        for (entry, chapter, level, pos, wander, show, hide) in c['stages']:
            sub = c['subname'] if entry != LYRA_CAPTIVE else 'Prisoner of the Defias'
            templates.append(creature_template(entry, c['name'], sub, c['display'], 35, c['equipment'], level,
                                               c['unit_class'], 'npc_zelda_companion', health=1.5, power=2.0))
            m, x, y, z, o = pos
            spawns.append(dict(guid=guid, id=entry, map=m, spawnMask=1, position_x=x, position_y=y, position_z=z,
                               orientation=o, spawntimesecsmin=60, spawntimesecsmax=60, spawndist=wander,
                               MovementType=1 if wander else 0))
            guid += 1
            stages.append(dict(entry=entry, show_quest=show[0], show_state=show[1], hide_quest=hide[0], hide_state=hide[1]))
    addons.append(dict(entry=LYRA_CAPTIVE, mount=0, stand_state=8, sheath_state=0, emote=0, moveflags=0, auras=None))
    texts.append(npc_text(CAPTIVE_TEXT[0], CAPTIVE_TEXT[1]))

    # Lady Prestor leaves the court once Onyxia is dead
    stages.append(dict(entry=KATRANA, show_quest=0, show_state=1, hide_quest=ONYXIA_QUEST, hide_state=1))
    for tid, text in KATRANA_TEXTS.items():
        texts.append(npc_text(tid, text))

    out.append(insert('creature_template', templates))
    out.append(insert('creature', spawns))
    out.append(insert('creature_template_addon', addons))
    out.append(insert('npc_text', texts))
    out.append(insert('gossip_menu', menus))
    out.append(insert('zelda_stage', stages))

    # quest items and their drops (quest-only, every time while needed)
    items, loot = [], []
    for (entry, name, display, desc, dropper) in QUEST_ITEMS:
        items.append(dict(entry=entry, **{'class': 12}, subclass=0, name=name, displayid=display, Quality=1, Flags=0,
                          BuyCount=1, BuyPrice=0, SellPrice=0, InventoryType=0, AllowableClass=-1, AllowableRace=-1,
                          ItemLevel=1, RequiredLevel=0, maxcount=1, stackable=1, bonding=4, description=desc,
                          Material=4, sheath=0))
        droppers = [dropper] if dropper else []
        if entry == 190511:
            droppers = [2338, 2339]
        for d in droppers:
            loot.append(dict(entry=d, item=entry, ChanceOrQuestChance=-100, groupid=0, mincountOrRef=1, maxcount=1,
                             condition_id=0, comments='Zelda of Warcraft quest drop'))
    out.append(insert('item_template', items))
    out.append(insert('creature_loot_template', loot))

    # quests
    quests, starts, ends = [], [], []
    by_id = {q['id']: q for q in Q}
    prev = {}
    chain = sorted(by_id)
    for a, b in zip(chain, chain[1:]):
        if b // 100 == a // 100:
            prev[b] = a
    for q in Q:
        qid, level = q['id'], q['level']
        row = dict(entry=qid, Method=2, ZoneOrSort=q['zone'], MinLevel=q['min'], MaxLevel=0, QuestLevel=level,
                   Type=QUEST_TYPE[q['kind']], RequiredRaces=0, RequiredClasses=0, SuggestedPlayers=0,
                   QuestFlags=0, SpecialFlags=0, PrevQuestId=prev.get(qid, 0), NextQuestId=0,
                   NextQuestInChain=qid + 1 if (qid + 1) in by_id and by_id[qid + 1]['giver'] == q['ender'] else 0,
                   SrcItemId=q.get('start_item', 0), SrcItemCount=1 if q.get('start_item') else 0,
                   Title=q['title'], Details=q['details'], Objectives=q['objectives'],
                   OfferRewardText=q['reward'], RequestItemsText=q['request'] or '', EndText='',
                   RewOrReqMoney=int(level * level * (16 if q['kind'] == 'raid' else 8)),
                   RewMoneyMaxLevel=int(level * 90), DetailsEmote1=1, OfferRewardEmote1=2, IncompleteEmote=1,
                   CompleteEmote=0)
        for n in range(1, 5):
            row['ObjectiveText%d' % n] = ''
            row['ReqItemId%d' % n] = 0
            row['ReqItemCount%d' % n] = 0
            row['ReqCreatureOrGOId%d' % n] = 0
            row['ReqCreatureOrGOCount%d' % n] = 0
        for n, (creature, count, text) in enumerate(q['kills'], start=1):
            row['ReqCreatureOrGOId%d' % n] = creature
            row['ReqCreatureOrGOCount%d' % n] = count
            row['ObjectiveText%d' % n] = text or ''
        for n, (item, count) in enumerate(q['items'], start=1):
            row['ReqItemId%d' % n] = item
            row['ReqItemCount%d' % n] = count
        for n in range(1, 7):
            row['RewChoiceItemId%d' % n] = 0
            row['RewChoiceItemCount%d' % n] = 0
        for n, item in enumerate(REWARDS.get(qid, []), start=1):
            row['RewChoiceItemId%d' % n] = item
            row['RewChoiceItemCount%d' % n] = 1
        row['RewItemId1'] = q.get('reward_item', 0)
        row['RewItemCount1'] = 1 if q.get('reward_item') else 0
        faction, value = q.get('rep', (0, 0))
        row['RewRepFaction1'] = faction
        row['RewRepValue1'] = value
        quests.append(row)
        starts.append(dict(id=q['giver'], quest=qid))
        ends.append(dict(id=q['ender'], quest=qid))
    out.append(insert('quest_template', quests))
    out.append(insert('creature_questrelation', starts))
    out.append(insert('creature_involvedrelation', ends))

    # Lady Prestor gives and takes quests
    out.append('UPDATE `creature_template` SET `NpcFlags` = `NpcFlags` | 3 WHERE `Entry` = %d;\n' % KATRANA)

    # both sides may take each other's quests (Zelda.CrossFaction makes the other side friendly)
    out.append('UPDATE `quest_template` SET `RequiredRaces` = 0 WHERE `RequiredRaces` IN (77, 178);\n')

    path = os.path.join(HERE, 'zelda-sql', '001_companions.sql')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', path, os.path.getsize(path), 'bytes;', len(templates), 'creatures,', len(quests), 'quests')


if __name__ == '__main__':
    main()
