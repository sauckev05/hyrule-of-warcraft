#!/usr/bin/env python3
"""Zelda of Warcraft: a craft needs only its own profession's materials. waived_reagents.json lists
(recipe spell, reagent item) pairs where the reagent comes from another profession (computed by
solo-wow/tools/compute_waived_reagents.py from Spell.dbc, SkillLineAbility.dbc and the skinning
loot). This writes zelda-sql/003_reagents.sql for the server and the same table for the Zelda
client (Benilla), which checks reagents itself before it asks the server to craft."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RUST = os.path.join(HERE, '..', '..', 'zelda-wow', 'benilla', 'crates', 'benilla-formats', 'src', 'spells',
                    'zelda_waived.rs')


def main():
    pairs = sorted({(int(s), int(i)) for s, i in json.load(open(os.path.join(HERE, 'waived_reagents.json')))})
    sql = ['-- Zelda of Warcraft: crafting reagents from another profession, no longer needed.',
           '-- Generated by build_reagents.py; applied by the server at startup.',
           'CREATE TABLE IF NOT EXISTS `zelda_waived_reagent` (',
           '  `spell` int unsigned NOT NULL,',
           '  `item` int unsigned NOT NULL,',
           '  PRIMARY KEY (`spell`, `item`)',
           ") ENGINE=MyISAM DEFAULT CHARSET=utf8 COMMENT='Zelda of Warcraft: reagents a recipe does not need';",
           'DELETE FROM `zelda_waived_reagent`;',
           'INSERT INTO `zelda_waived_reagent` (`spell`, `item`) VALUES']
    sql.append(',\n'.join('(%d,%d)' % p for p in pairs) + ';')
    with open(os.path.join(HERE, 'zelda-sql', '003_reagents.sql'), 'w', newline='\n') as f:
        f.write('\n'.join(sql) + '\n')

    rows = []
    for k in range(0, len(pairs), 6):
        rows.append('    ' + ' '.join('(%d, %d),' % p for p in pairs[k:k + 6]))
    rust = ['//! Zelda of Warcraft: crafting reagents that come from another profession, which a recipe no',
            '//! longer needs (the Azeroth Solo server waives the same ones). Generated by',
            '//! solo-wow/content/build_reagents.py - do not edit.',
            '',
            '/// `(recipe spell, reagent item)`, sorted.',
            'static WAIVED: &[(u32, u32)] = &[',
            *rows,
            '];',
            '',
            '/// True when the recipe `spell` does not need the reagent `item`.',
            'pub(crate) fn is_waived(spell: u32, item: u32) -> bool {',
            '    WAIVED.binary_search(&(spell, item)).is_ok()',
            '}',
            '']
    with open(RUST, 'w', newline='\n') as f:
        f.write('\n'.join(rust))
    print('wrote', len(pairs), 'waived reagents')


if __name__ == '__main__':
    main()
